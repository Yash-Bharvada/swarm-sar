"""Actual Chrome QA for the reader and generated PDF; no simulated test results."""
import asyncio,json,re,subprocess,os
from pathlib import Path
from playwright.async_api import async_playwright
SITE=Path(__file__).resolve().parents[1]; DIST=SITE/'dist'; QA=SITE/'qa'; QA.mkdir(exist_ok=True)
BASE=os.environ.get('SWARM_BOOK_URL','http://127.0.0.1:8088')
async def main():
    book=json.loads((DIST/'book.json').read_text()); checks=[]; errors=[]
    def check(name,ok,detail=None):
        if not ok: raise AssertionError(name+': '+str(detail))
        checks.append(dict(name=name,passed=True,detail=detail))
    paths={f['path'] for f in book['files']}
    check('Every chapter has pages',all(any(p['chapter']==c['id'] for p in book['pages']) for c in book['chapters']))
    check('Every cited repository path exists',all(s in paths for p in book['pages'] for s in p['sources']))
    check('Every audio track exists',all((DIST/p['audio']).is_file() for p in book['pages']))
    check('All tracks have measured nonzero duration',all(p.get('duration',0)>5 for p in book['pages']))
    check('All readable atlas files exist',all((DIST/f['url']).is_file() for f in book['files'] if f['readable']))
    m4b=json.loads(subprocess.check_output(['/opt/homebrew/bin/ffprobe','-v','quiet','-print_format','json','-show_chapters','-show_format',str(DIST/'swarm-sar-fieldbook.m4b')]))
    check('Complete audiobook has page chapter markers',len(m4b['chapters'])==len(book['pages']),len(m4b['chapters']))
    async with async_playwright() as pw:
        browser=await pw.chromium.launch(channel='chrome',headless=True)
        context=await browser.new_context(viewport={'width':1600,'height':1100},device_scale_factor=1)
        page=await context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
        await page.goto(BASE,wait_until='networkidle');await page.locator('.cover-title').wait_for()
        await page.screenshot(path=str(QA/'desktop-cover.png'),full_page=True)
        check('Cover renders actual screenshot',await page.locator('.cover-visual img').evaluate('(i)=>i.complete&&i.naturalWidth>0'))
        check('Desktop has no horizontal overflow',await page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        await page.get_by_role('button',name='Open the book').click();await page.wait_for_function('current===1')
        check('Page-turn button changes page',await page.locator('h1').inner_text()=='A note to the reader')
        await page.keyboard.press('ArrowRight');await page.wait_for_function('current===2')
        check('Keyboard page turning works',await page.locator('h1').inner_text()=='Four people, one shared story')
        await page.get_by_role('button',name='Bookmark this page',exact=True).click()
        await page.get_by_role('button',name='View bookmarks').click()
        check('Bookmark is listed',await page.locator('#modal-content').get_by_text('Four people, one shared story').count()==1)
        await page.get_by_role('button',name='Close dialog',exact=True).click()
        await page.keyboard.press('/');await page.locator('#search-input').fill('MAPPO')
        check('Full book search finds technical discussion',await page.locator('#search-results .result').count()>=2)
        await page.locator('#search-input').fill('zzzznoresultzzzz')
        check('Search empty state is clear',await page.locator('#search-results').get_by_text('No pages found.',exact=False).count()==1)
        await page.get_by_role('button',name='Close dialog',exact=True).click()
        await page.locator('#open-files').click();await page.locator('#file-input').fill('backend/ppo_service.py')
        check('Atlas finds exact backend file',await page.locator('#file-results .result').count()==1)
        await page.locator('#file-results .result').click();await page.locator('.code-line').first.wait_for()
        check('Actual source opens with line numbers','Local HTTP mission service' in await page.locator('.code-viewer').inner_text())
        await page.get_by_role('button',name='Close dialog',exact=True).click()
        reward=next(p['id'] for p in book['pages'] if p['visual']=='reward')
        await page.evaluate('(i)=>navigate(i)',reward);await page.locator('#new-cells').fill('100');await page.locator('#new-cells').dispatch_event('input')
        check('Reward illustration updates its calculation','1.99' in await page.locator('#reward-result').inner_text())
        ppo=next(p['id'] for p in book['pages'] if p['visual']=='ppo')
        await page.evaluate('(i)=>navigate(i)',ppo);await page.locator('#ratio').fill('110');await page.locator('#ratio').dispatch_event('input')
        check('PPO clipping example updates',await page.locator('#clip-objective').inner_text()=='2.20')
        await page.wait_for_timeout(700);await page.screenshot(path=str(QA/'desktop-ppo.png'),full_page=True)
        network=next(p['id'] for p in book['pages'] if p['visual']=='network')
        await page.evaluate('(i)=>navigate(i)',network);await page.locator('#loss').fill('75');await page.locator('#loss').dispatch_event('input')
        check('Radio illustration updates',await page.locator('#packet-label').text_content()=='25 / 100')
        await page.evaluate('navigate(1)');await page.get_by_role('button',name='Play narration',exact=True).click()
        await page.wait_for_function('audio.currentTime>0.2',timeout=15000)
        check('Real recorded audio plays',await page.evaluate('!audio.paused && audio.duration>5'))
        await page.get_by_role('button',name='Pause narration',exact=True).click()
        check('Pause stops playback',await page.evaluate('audio.paused'))
        await page.locator('#speed').click();check('Speed setting applies',await page.evaluate('audio.playbackRate')==1.25)
        await page.evaluate('audio.currentTime=audio.duration-0.3');await page.wait_for_function('!audio.seeking');await page.get_by_role('button',name='Play narration',exact=True).click();await page.wait_for_function('current===2',timeout=10000)
        check('Audio completion turns page and continues',await page.evaluate('current===2'))
        await page.evaluate('audio.pause()');await page.evaluate('navigate(8)')
        check('Actual image modal expands',await page.locator('[data-expand]').count()>0)
        await page.locator('[data-expand]').first.click();check('Image modal is visible',await page.locator('#image-modal').is_visible());await page.locator('.image-close').click()
        await page.evaluate('navigate(0)');await page.reload(wait_until='networkidle');check('Reading place survives reload',await page.evaluate('current')==0)
        for p in book['pages']:
            await page.evaluate('(i)=>navigate(i,{animate:false})',p['id'])
            check('Desktop page '+str(p['id']+1)+' renders without overflow',await page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        latest=next(p['id'] for p in book['pages'] if p['chapter']==16)
        await page.evaluate('(i)=>navigate(i)',latest)
        await page.get_by_role('button',name='Play narration',exact=True).click()
        await page.wait_for_function('audio.currentTime>0.2',timeout=15000)
        check('New SLAM chapter recorded narration plays',await page.evaluate('audio.duration>5 && !audio.paused'))
        await page.evaluate('audio.pause()')
        observatory=next(p['id'] for p in book['pages'] if p['visual']=='observatory-map')
        await page.evaluate('(i)=>navigate(i)',observatory)
        await page.locator('img[src="assets/observatory-map.png"]').wait_for()
        check('Updated observatory photograph loads',await page.locator('img[src="assets/observatory-map.png"]').evaluate('(i)=>i.decode().then(()=>i.naturalWidth>0)'))
        await page.screenshot(path=str(QA/'desktop-slam-extension.png'),full_page=True)
        check('Extended edition has 20 chapters and 91 narrated pages',len(book['chapters'])==20 and len(book['pages'])==91)
        await context.close()
        mobile=await browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
        mp=await mobile.new_page();mp.on('pageerror',lambda e:errors.append(str(e)));await mp.goto(BASE+'/#page=1',wait_until='networkidle')
        await mp.screenshot(path=str(QA/'mobile-cover.png'),full_page=True)
        check('Mobile has no horizontal overflow',await mp.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        await mp.get_by_role('button',name='Open contents').click();check('Mobile contents opens',await mp.locator('#sidebar').evaluate('(e)=>e.classList.contains("open")'))
        await mp.locator('[data-chapter="8"]').click();check('Mobile chapter navigation closes contents',not await mp.locator('#sidebar').evaluate('(e)=>e.classList.contains("open")'))
        for p in book['pages']:
            await mp.evaluate('(i)=>navigate(i,{animate:false})',p['id'])
            check('Mobile page '+str(p['id']+1)+' renders without overflow',await mp.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        await mp.evaluate('(i)=>navigate(i)',ppo);await mp.wait_for_timeout(700);await mp.screenshot(path=str(QA/'mobile-ppo.png'),full_page=True)
        await mobile.close()
        printpage=await browser.new_page();await printpage.goto(BASE+'/print.html',wait_until='networkidle');await printpage.pdf(path=str(DIST/'swarm-sar-fieldbook.pdf'),format='A4',print_background=True,prefer_css_page_size=True)
        pdf=(DIST/'swarm-sar-fieldbook.pdf').read_bytes();check('Full illustrated PDF generated',len(pdf)>100000,len(pdf))
        check('Browser reported no script errors',not errors,errors)
        await browser.close()
    report=dict(checks=checks,passed=len(checks),readerPages=len(book['pages']),chapters=len(book['chapters']),words=book['wordCount'],audioMinutes=round(book['audioDuration']/60,1),files=len(book['files']),browserErrors=errors,pdfPageCount=len(re.findall(rb'/Type /Page\b',pdf)),sourceRevision=book['revision'])
    (QA/'verification.json').write_text(json.dumps(report,indent=2));print(json.dumps({k:v for k,v in report.items() if k!='checks'}))
asyncio.run(main())
