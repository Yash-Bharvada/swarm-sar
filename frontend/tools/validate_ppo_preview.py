"""Verify live PPO setup preview against the running Python service, without fixtures."""
import argparse, json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('--url', default='http://127.0.0.1:5173')
parser.add_argument('--browser-executable')
args = parser.parse_args()
base = args.url.rstrip('/')
cache = sorted((Path.home() / 'Library/Caches/ms-playwright').glob('chromium_headless_shell-*/chrome-headless-shell-mac-arm64/chrome-headless-shell'))
browser_executable = args.browser_executable or (str(cache[-1]) if cache else None)
out = Path('artifacts/ppo_preview')
out.mkdir(parents=True, exist_ok=True)
checks, errors, posts = [], [], []
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path=browser_executable, args=['--enable-unsafe-swiftshader'])
    page = browser.new_page(viewport=dict(width=1512, height=1000))
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: posts.append(r.url) if r.method == 'POST' else None)
    page.goto(base + '/')
    page.evaluate("async()=>{window.store=(await import('/src/store/simStore.ts')).useSim}")
    page.get_by_role('button', name='Controller settings', exact=True).click()
    page.get_by_role('radio', name='PPO', exact=True).click()
    page.wait_for_function("store.getState().ppoPhase==='preview' && store.getState().engine.mission && store.getState().engine.scenario.width===32")
    assert not any(u.endswith('/missions') for u in posts)
    expect(page.get_by_role('button', name='Launch mission', exact=True)).to_be_disabled()
    checks.append('PPO opens a Python-generated preview without creating a session')
    page.get_by_label('PPO map size', exact=True).select_option('40')
    page.get_by_label('PPO layout', exact=True).select_option('maze')
    page.get_by_label('PPO rovers', exact=True).fill('4')
    page.get_by_label('PPO drones', exact=True).fill('2')
    page.get_by_label('PPO map', exact=True).select_option('10081')
    page.wait_for_function("store.getState().engine.scenario.width===40 && store.getState().engine.scenario.seed===10081 && store.getState().engine.scenario.name==='PPO Maze' && store.getState().engine.robots.length===6")
    checks.append('Map seed, size, layout and fleet update before Create mission')
    page.get_by_label('PPO radio', exact=True).uncheck()
    page.get_by_label('PPO battery mode', exact=True).select_option('unlimited')
    page.get_by_label('Mission time limit', exact=True).select_option('custom')
    page.get_by_label('Mission duration in minutes', exact=True).fill('2')
    page.wait_for_function("!store.getState().engine.network.enabled && !store.getState().settings.batteryLimited && store.getState().engine.maxSteps===120")
    assert not any(u.endswith('/missions') for u in posts)
    checks.append('Radio, battery and duration preview without a session')
    page.get_by_label('PPO map size', exact=True).select_option('24')
    page.get_by_label('PPO map size', exact=True).select_option('48')
    page.get_by_label('PPO map size', exact=True).select_option('40')
    page.wait_for_function("store.getState().engine.scenario.width===40 && store.getState().settings.timeLimit===120")
    page.wait_for_timeout(700)
    assert page.evaluate('store.getState().engine.scenario.width') == 40
    page.get_by_role('button', name='Refresh preview', exact=True).click()
    page.wait_for_timeout(700)
    assert not any(u.endswith('/missions') for u in posts)
    checks.append('Rapid edits and Refresh preview never create a mission')
    before = page.evaluate("({grid:Array.from(store.getState().engine.scenario.grid.cells), robots:store.getState().engine.robots.map(r=>[r.name,r.x,r.y]),seed:store.getState().engine.scenario.seed})")
    page.screenshot(path=str(out / 'live-preview.png'), full_page=True)
    page.get_by_role('button', name='Create mission', exact=True).click()
    page.wait_for_function("store.getState().ppoPhase==='ready'")
    after = page.evaluate("({grid:Array.from(store.getState().engine.scenario.grid.cells), robots:store.getState().engine.robots.map(r=>[r.name,r.x,r.y]),seed:store.getState().engine.scenario.seed})")
    assert before == after
    expect(page.get_by_role('button', name='Launch mission', exact=True)).to_be_enabled()
    assert len([u for u in posts if u.endswith('/missions')]) == 1
    checks.append('Create mission matches preview geometry and enables Launch')
    page.get_by_role('button', name='Launch mission', exact=True).click()
    page.wait_for_function('store.getState().engine.step>0')
    checks.append('Created mission runs actual PPO inference')
    page.get_by_role('button', name='Pause mission', exact=True).click()
    mission = page.evaluate('store.getState().engine.mission')
    page.request.delete(base + '/api/ppo/missions/' + mission)
    browser.close()
assert not errors, errors
report = dict(passed=True, checks=checks, browser_errors=errors, limits='Actual local Python PPO service and development maps; no policy retraining.')
(out / 'validation.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
