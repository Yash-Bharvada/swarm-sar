"""Actual browser mission QA plus explicitly synthetic ROS/PPO contract checks."""
import argparse,json,time,re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect


def main():
    args=argparse.ArgumentParser()
    args.add_argument('--url',default='http://127.0.0.1:5184')
    args.add_argument('--output',default='artifacts/observatory_ui')
    args.add_argument('--browser-executable',default=None)
    a=args.parse_args();out=Path(a.output);out.mkdir(parents=True,exist_ok=True)
    checks=[];errors=[]
    def check(name,value):
        assert value,name
        checks.append(name)
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,executable_path=a.browser_executable,args=['--enable-unsafe-swiftshader'])
        page=browser.new_page(viewport=dict(width=1512,height=1000))
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(a.url+'/?mode=observatory');expect(page.locator('.observatory-canvas')).to_be_visible()
        page.get_by_role('button',name='Launch mission',exact=True).click()
        page.wait_for_timeout(1800)
        page.get_by_role('button',name='Pause mission',exact=True).click()
        page.evaluate("async()=>{const {useSim}=await import('/src/store/simStore.ts');window.__obStore=useSim;window.__obEngine=useSim.getState().engine}")
        step=page.evaluate('window.__obStore.getState().engine.step')
        check('Actual browser mission advances in dedicated page',step>0)
        page.get_by_role('button',name=re.compile('^Messages')).click()
        check('Actual packet records populate stream',page.locator('.ob-packet-row').count()>0)
        page.get_by_role('button',name='Close messages').click()
        page.get_by_role('button',name='Top-down camera',exact=True).click()
        expect(page.get_by_role('button',name='Isometric camera',exact=True)).to_have_attribute('aria-pressed','true')
        page.get_by_role('button',name='Reset view',exact=True).click()
        expect(page.get_by_role('button',name='Top-down camera',exact=True)).to_be_visible()
        check('Top-down camera and reset controls work',True)
        page.get_by_role('button',name='Map layers',exact=True).click()
        packet_layer=page.get_by_role('button',name='Packets',exact=True)
        packet_layer.click();expect(packet_layer).to_have_attribute('aria-pressed','false')
        packet_layer.click();page.get_by_role('button',name='Map layers',exact=True).click()
        check('Map layer toggles expose actual on/off state',True)
        page.screenshot(path=str(out/'desktop-spatial.png'),full_page=True)
        page.get_by_role('button',name='Peer network',exact=True).click();page.wait_for_timeout(300)
        page.screenshot(path=str(out/'desktop-neural.png'),full_page=True)
        page.locator('.ob-agent').first.click();expect(page.get_by_role('button',name='Clear agent selection')).to_be_visible()
        page.get_by_role('button',name='Clear agent selection').click()
        page.get_by_role('button',name='Freeze visualization').click();expect(page.get_by_role('button',name='Resume visualization')).to_be_visible()
        page.get_by_role('button',name='Resume visualization').click()
        page.get_by_role('button',name=re.compile('^Messages')).click()
        page.get_by_label('Filter packet stream').select_option('dropped')
        check('Dropped-message filter respects actual state',all('dropped' in (e.get_attribute('class') or '') for e in page.locator('.ob-packet-state').all()))
        page.get_by_label('Filter packet stream').select_option('all')
        with page.expect_download() as download:page.get_by_role('button',name='Export telemetry').click()
        exported=json.loads(Path(download.value.path()).read_text())
        check('Export contains real source and mission agents',exported['source']=='browser' and len(exported['agents'])==4)
        page.get_by_role('button',name='Close messages').click()
        page.locator('canvas').evaluate("canvas=>canvas.dispatchEvent(new Event('webglcontextlost',{cancelable:true}))")
        expect(page.get_by_text('The 3D view needs a moment.')).to_be_visible()
        expect(page.get_by_role('button',name=re.compile('^Messages'))).to_be_visible()
        page.get_by_role('button',name='Retry 3D view',exact=True).click()
        expect(page.locator('canvas')).to_be_visible()
        check('Graphics recovery preserves message controls and restores 3D',True)
        page.get_by_role('button',name='Back to simulation',exact=True).click()
        expect(page.get_by_role('link',name='Open the English audio fieldbook')).to_have_attribute('href','https://swarmsar.vercel.app')
        expect(page.get_by_role('button',name='Swarm intelligence',exact=True)).to_be_visible()
        check('Returning to world retains exact engine and paused step',page.evaluate('window.__obStore.getState().engine===window.__obEngine && window.__obStore.getState().engine.step===%d'%step))
        page.get_by_role('button',name='Swarm intelligence',exact=True).click()
        expect(page.locator('.observatory')).to_be_visible()
        check('Navigation retains mission status',page.evaluate("window.__obStore.getState().status==='paused'"))
        # A synthetic backend fixture checks that navigation never recreates the PPO mission.
        fixture=json.loads((Path(__file__).resolve().parents[1]/'src/tests/fixtures/pythonInitial.json').read_text());posts=[]
        def api(route):
            if route.request.method=='POST' and route.request.url.endswith('/missions'):posts.append(route.request.url)
            route.fulfill(status=200,content_type='application/json',body=json.dumps(fixture))
        page.route('**/api/ppo/**',api)
        page.evaluate("window.__obStore.setState({controllerMode:'ppo',ppoPhase:'connecting'})")
        page.wait_for_function("window.__obStore.getState().ppoPhase==='ready'")
        creates=len(posts)
        page.get_by_role('button',name='Back to simulation',exact=True).click()
        page.get_by_role('button',name='Swarm intelligence',exact=True).click();page.wait_for_timeout(400)
        check('PPO bridge remains mounted across view navigation',len(posts)==creates)
        page.close()
        mobile=browser.new_page(viewport=dict(width=390,height=844),is_mobile=True,has_touch=True)
        mobile.on('pageerror',lambda e:errors.append(str(e)));mobile.goto(a.url+'/?mode=observatory')
        expect(mobile.locator('.observatory-canvas')).to_be_visible();mobile.wait_for_timeout(300)
        check('Mobile has no horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        mobile.screenshot(path=str(out/'mobile-neural.png'),full_page=True);mobile.close()
        # Explicitly synthetic rosbridge fixtures, never saved as live SLAM evidence.
        ros=browser.new_page(viewport=dict(width=1440,height=1000));ros.on('pageerror',lambda e:errors.append(str(e)))
        # Control fixture wall time so software-rendering delays cannot age packets between assertions.
        fixture_wall=int(time.time()*1000);ros.clock.set_fixed_time(fixture_wall)
        sockets=[];requests=[]
        def route_socket(ws):
            sockets.append(ws)
            def receive(raw):
                request=json.loads(raw);requests.append(request)
                if request.get('op')=='call_service':
                    ws.send(json.dumps(dict(op='service_response',id=request['id'],result=True,values=dict(success=True,message='SYNTHETIC service acknowledgement'))))
            ws.on_message(receive)
        ros.route_web_socket('ws://fixture.invalid:9090/',route_socket)
        ros.goto(a.url+'/?mode=ros');expect(ros.locator('.ob-welcome')).to_be_visible()
        check('Legacy ROS route opens unified clean observatory',ros.locator('.ros-live').count()==0)
        check('No placeholder robots or map rendered while disconnected',ros.locator('.ob-agent').count()==0 and ros.locator('canvas').count()==0)
        ros.screenshot(path=str(out/'ros-disconnected.png'),full_page=True)
        ros.get_by_role('button',name='Connect ROS bridge',exact=True).click();ros.get_by_label('ROS bridge URL').fill('ws://fixture.invalid:9090')
        ros.get_by_role('button',name='Connect',exact=True).click()
        ros.wait_for_function("document.querySelector('.ob-connection-status').textContent.includes('connected')")
        ros.keyboard.press('Escape');expect(ros.get_by_role('dialog')).to_have_count(0)
        def send(topic,msg):sockets[0].send(json.dumps(dict(op='publish',topic=topic,msg=msg)))
        def clock(t):send('/clock',dict(clock=dict(sec=t,nanosec=0)))
        clock(10)
        send('/rover_0/estimated_odom',dict(header=dict(frame_id='map'),pose=dict(pose=dict(position=dict(x=1,y=2),orientation=dict(z=0,w=1)))) )
        health=dict(agent='rover_0',run='SYNTHETIC-OBSERVATORY-TEST',state='tracking',source='slam_toolbox',local_known=20,peer_known=3,map_age=.1,pose_age=.1,claims={})
        send('/rover_0/slam_health',dict(data=json.dumps(health)))
        send('/rover_0/local_slam_map',dict(header=dict(frame_id='map'),info=dict(width=2,height=2,resolution=1,origin=dict(position=dict(x=0,y=0),orientation=dict(x=0,y=0,z=0,w=1))),data=[0,100,-1,0]))
        clock(11)
        stats=dict(sim_time=11,metrics=dict(attempted=5,delivered=1,bytes_sent=2048),isolated=[])
        send('/swarm/network/stats',dict(data=json.dumps(stats)))
        send('/swarm/network/events',dict(data=json.dumps(dict(event='transport_delivered',source='rover_0',target='rover_1',channel='slam_peer',sequence=1,sim_time=11))))
        ros.get_by_role('button',name=re.compile('^Messages')).click()
        expect(ros.locator('.ob-packet-row')).to_have_count(1)
        check('ROS subscriptions render incoming packet telemetry',ros.locator('.ob-packet-state.delivered').count()==1)
        ros.get_by_role('button',name='Close messages').click()
        ros.get_by_role('button',name='Inspect rover_0',exact=True).click()
        expect(ros.get_by_role('button',name='Isolate radio',exact=True)).to_be_enabled()
        ros.get_by_role('button',name='Isolate radio',exact=True).click()
        expect(ros.get_by_text('Request acknowledged. Status follows ROS telemetry.')).to_be_visible()
        check('Isolation acknowledgement does not fabricate radio state',ros.get_by_role('button',name='Isolate radio',exact=True).count()==1)
        stats['isolated']=['rover_0'];send('/swarm/network/stats',dict(data=json.dumps(stats)))
        expect(ros.get_by_role('button',name='Reconnect radio',exact=True)).to_be_visible()
        check('Preserved radio controls follow actual ROS telemetry',any(r.get('service')=='/swarm/network/isolate/rover_0' for r in requests))
        ros.clock.set_fixed_time(fixture_wall+5000)
        expect(ros.get_by_role('button',name='Reconnect radio',exact=True)).to_be_disabled()
        check('Aged ROS telemetry disables radio commands',True)
        ros.get_by_role('button',name='ROS connection',exact=True).click();ros.get_by_role('button',name='Disconnect',exact=True).click();ros.keyboard.press('Escape')
        expect(ros.locator('.ob-stamp')).to_contain_text('WAITING / STALE')
        check('Disconnected ROS shows stale state', 'WAITING / STALE' in ros.locator('.ob-stamp').inner_text())
        check('ROS observatory publishes no velocity or map commands',not any(r.get('op')=='publish' for r in requests))
        ros.close();browser.close()
    check('No browser runtime errors',not errors)
    report=dict(passed=True,checks=checks,browser_errors=errors,limits='Browser mission evidence is real simulator telemetry. ROS/PPO fixtures test UI contracts only, not live SLAM or policy inference.')
    (out/'validation.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))

if __name__=='__main__':main()
